"""Regenerate `src/omnigraph/_models.py` and `_version.py` from the pinned spec.

uv run python scripts/generate.py           # write
uv run python scripts/generate.py --check   # fail when the files are stale
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "spec" / "openapi.json"
MODELS = ROOT / "src" / "omnigraph" / "_models.py"
VERSION = ROOT / "src" / "omnigraph" / "_version.py"

HEADER = '''\
"""Wire models generated from spec/openapi.json. Do not edit by hand.

Regenerate with `uv run python scripts/generate.py`.
"""

'''


def server_version() -> str:
    data = tomllib.loads((ROOT / "pyproject.toml").read_text())
    return str(data["tool"]["omnigraph"]["server-version"])


def render_models() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "models.py"
        subprocess.run(
            [
                "datamodel-codegen",
                "--input",
                str(SPEC),
                "--input-file-type",
                "openapi",
                "--output-model-type",
                "typing.TypedDict",
                "--target-python-version",
                "3.11",
                "--use-standard-collections",
                "--use-union-operator",
                "--enum-field-as-literal",
                "all",
                "--use-schema-description",
                "--disable-timestamp",
                "--output",
                str(out),
            ],
            check=True,
        )
        body = out.read_text()
    # Drop the generator's own banner; ours names the source and the command.
    lines = body.splitlines(keepends=True)
    while lines and (lines[0].startswith("#") or not lines[0].strip()):
        lines.pop(0)
    return HEADER + "".join(lines)


def render_version() -> str:
    spec_version = json.loads(SPEC.read_text())["info"]["version"]
    pinned = server_version()
    if spec_version != pinned:
        sys.exit(f"spec/openapi.json is {spec_version}, pyproject pins {pinned}")
    major, minor, _ = pinned.split(".")
    return (
        '"""Generated by scripts/generate.py. Do not edit by hand."""\n\n'
        f'SERVER_VERSION = "{pinned}"\n'
        f'HTTP_API_CONTRACT = "{major}.{minor}"\n'
        'HTTP_API_CONTRACT_HEADER = "Omnigraph-Http-Api"\n'
    )


def main() -> None:
    check = "--check" in sys.argv[1:]
    stale = []
    for path, text in ((MODELS, render_models()), (VERSION, render_version())):
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.write_text(text)
    if stale:
        sys.exit(f"stale generated files: {', '.join(map(str, stale))}")


if __name__ == "__main__":
    main()
