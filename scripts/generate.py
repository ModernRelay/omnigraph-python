"""Regenerate `src/omnigraph/_models.py` and `_version.py` from the pinned spec.

uv run python scripts/generate.py           # write
uv run python scripts/generate.py --check   # fail when the files are stale
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "spec" / "openapi.json"
MODELS = ROOT / "src" / "omnigraph" / "_models.py"
VERSION = ROOT / "src" / "omnigraph" / "_version.py"

HEADER_NAME = "Omnigraph-Http-Api"

HEADER = '''\
"""Wire models generated from spec/openapi.json. Do not edit by hand.

Regenerate with `uv run python scripts/generate.py`.
"""

'''


def _pyproject() -> dict[str, Any]:
    return tomllib.loads((ROOT / "pyproject.toml").read_text())


def server_version() -> str:
    return str(_pyproject()["tool"]["omnigraph"]["server-version"])


def check_package_version(release: str) -> None:
    """The package's major.minor is the server release it is generated from;
    its patch number is the SDK's own, for fixes that change nothing on the
    wire."""
    version = str(_pyproject()["project"]["version"])
    m = re.match(r"(\d+)\.(\d+)", version)
    if m is None or f"{m.group(1)}.{m.group(2)}" != release:
        sys.exit(f"package version {version} must start with server {release}")


def http_api_contract(spec: dict[str, Any]) -> str:
    """The `Omnigraph-Http-Api` value the spec requires: the one enum value of
    that header parameter, the same on every operation that declares it. A
    server release does not change it unless the wire contract changes, so it
    is read here, never derived from the release number."""
    values: set[tuple[str, ...]] = set()
    for item in spec["paths"].values():
        for op in item.values():
            if not isinstance(op, dict):
                continue
            for param in op.get("parameters", []):
                if param.get("in") == "header" and param.get("name") == HEADER_NAME:
                    values.add(tuple(param["schema"]["enum"]))
    if len(values) != 1 or len(next(iter(values))) != 1:
        sys.exit(f"spec must require one {HEADER_NAME} value, found {sorted(values)}")
    return next(iter(values))[0]


def render_models() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "models.py"
        subprocess.run(
            [
                "datamodel-codegen",
                "--input",
                str(SPEC),
                "--input-file-type",
                "openapi",
                "--output-model-type",
                "typing.TypedDict",
                "--target-python-version",
                "3.11",
                "--use-standard-collections",
                "--use-union-operator",
                "--enum-field-as-literal",
                "all",
                "--use-schema-description",
                "--disable-timestamp",
                "--output",
                str(out),
            ],
            check=True,
        )
        body = out.read_text()
    # Drop the generator's own banner; ours names the source and the command.
    lines = body.splitlines(keepends=True)
    while lines and (lines[0].startswith("#") or not lines[0].strip()):
        lines.pop(0)
    return HEADER + "".join(lines)


def render_version() -> str:
    spec = json.loads(SPEC.read_text())
    spec_version = spec["info"]["version"]
    pinned = server_version()
    if spec_version != pinned:
        sys.exit(f"spec/openapi.json is {spec_version}, pyproject pins {pinned}")
    major, minor, _ = pinned.split(".")
    check_package_version(f"{major}.{minor}")
    return (
        '"""Generated by scripts/generate.py. Do not edit by hand."""\n\n'
        f'SERVER_VERSION = "{pinned}"\n'
        f'HTTP_API_CONTRACT = "{http_api_contract(spec)}"\n'
        f'HTTP_API_CONTRACT_HEADER = "{HEADER_NAME}"\n'
    )


def main() -> None:
    check = "--check" in sys.argv[1:]
    stale = []
    for path, text in ((MODELS, render_models()), (VERSION, render_version())):
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.write_text(text)
    if stale:
        sys.exit(f"stale generated files: {', '.join(map(str, stale))}")


if __name__ == "__main__":
    main()
